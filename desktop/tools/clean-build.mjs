// clean-build.mjs  Remove build output after a release build.
//
//   npm run clean                 (in app/; or: node tools/clean-build.mjs)
//   npm run clean -- --all        also the development build and the current engine build
//   npm run clean -- --dry-run    only list what would be removed
//
// Default (after a release build; the installer is copied to dist/ by build-release.mjs):
//   app/src-tauri/target/release      Rust release build and the installer bundle
//   app/build                         front-end build
//   engine-matlab/build/<version>     engine builds of other versions than the current one
// --all also removes
//   app/src-tauri/target              everything, including the development (debug) build:
//                                     the next `npm run dev:app` rebuilds Rust from scratch
//   app/.svelte-kit                   regenerated by `svelte-kit sync`
//   engine-matlab/build/<current>     exe, installer and generated files of the current version
// Always kept: dist/ (app installers), engine-matlab/build/dist (the engine installer the
// release build needs), node_modules.
//
// SPDX-License-Identifier: GPL-3.0-or-later

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { actipassVersion } from "./build-release.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "..");
const args = process.argv.slice(2);
const all = args.includes("--all");
const dryRun = args.includes("--dry-run") || args.includes("-n");
const unknown = args.filter((a) => !["--all", "--dry-run", "-n"].includes(a));
if (unknown.length) {
  console.error(`clean-build: unknown option ${unknown.join(" ")} (use --all, --dry-run)`);
  process.exit(1);
}

let current = "";
try {
  current = actipassVersion().version;
} catch (e) {
  console.warn(`clean-build: cannot read the Actipass version (${e.message}); keeping all engine builds`);
}

const targetDir = path.join(repo, "app", "src-tauri", "target");
const targets = all
  ? [targetDir, path.join(repo, "app", ".svelte-kit")]
  : [path.join(targetDir, "release")];
targets.push(path.join(repo, "app", "build"));

const engineBuild = path.join(repo, "engine-matlab", "build");
if (current && fs.existsSync(engineBuild)) {
  for (const d of fs.readdirSync(engineBuild, { withFileTypes: true })) {
    if (!d.isDirectory() || d.name === "dist") continue;
    if (/^\d+\.\d+\.\d+$/.test(d.name) && (all || d.name !== current)) targets.push(path.join(engineBuild, d.name));
  }
}

function size(p) {
  const st = fs.lstatSync(p);
  if (!st.isDirectory()) return st.size;
  let n = 0;
  for (const e of fs.readdirSync(p)) n += size(path.join(p, e));
  return n;
}
const fmt = (b) => (b >= 2 ** 30 ? `${(b / 2 ** 30).toFixed(2)} GB` : `${(b / 2 ** 20).toFixed(1)} MB`);

let total = 0;
let failed = false;
for (const t of targets) {
  if (!fs.existsSync(t)) continue;
  const s = size(t);
  total += s;
  const rel = path.relative(repo, t).replaceAll("\\", "/");
  if (dryRun) {
    console.log(`would remove ${rel} (${fmt(s)})`);
    continue;
  }
  try {
    fs.rmSync(t, { recursive: true, force: true, maxRetries: 3 });
    console.log(`removed ${rel} (${fmt(s)})`);
  } catch (e) {
    failed = true;
    console.error(`clean-build: cannot remove ${rel}: ${e.message} (close the app and \`tauri dev\` first)`);
  }
}
console.log(total ? `clean-build: ${dryRun ? "would free" : "freed"} ${fmt(total)}` : "clean-build: nothing to remove");
process.exit(failed ? 1 : 0);
